"""api/citations.py — Simple BibTeX export for interview demo.

The orchestrator already returns a list of source strings in the SSE ``done``
event.  This endpoint lets the UI request a downloadable BibTeX file for a
given session.  For the demo we don’t persist sources per session – the UI can
pass the sources as a query parameter (multiple ``source=...`` entries).  The
handler builds a minimal ``@misc`` entry for each source and returns the
concatenated BibTeX text as ``text/plain``.
"""

from fastapi import APIRouter, Query, Response

router = APIRouter()

@router.get("/citations/{session_id}")
def export_citations(
    session_id: str,
    sources: list[str] = Query(default=[]),
) -> Response:
    """Return a tiny BibTeX document for the supplied *sources*.

    Args:
        session_id: Identifier of the conversation (included for symmetry –
            the demo does not store anything server‑side).
        sources: List of source strings (e.g. URLs or file names) passed as
            repeated query parameters ``?source=...&source=...``.

    Returns:
        ``Response`` with ``text/plain`` content containing BibTeX entries.
    """
    if not sources:
        bibtex = f"% No sources supplied for session {session_id}\n"
    else:
        entries = []
        for idx, src in enumerate(sources, start=1):
            safe_src = (
                src.replace("\\", "\\\\")
                .replace("{", "\\{")
                .replace("}", "\\}")
                .replace(",", "\\,")
            )
            entries.append(
                f"@misc{{source{idx},\n"
                f"  title = {{{safe_src}}},\n"
                "  note = {Generated by MedAssist-AI}\n"
                "}"
            )
        bibtex = "\n\n".join(entries)

    return Response(
        content=bibtex,
        media_type="text/plain",
        headers={"Content-Disposition": 'attachment; filename="citations.bib"'},
    )
